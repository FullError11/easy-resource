#pragma once

#include "global.h"
#include <filesystem>
#include <functional>
#include <iostream>
#include <stdexcept>
#include <string>
#include <string_view>
#include <vector>

class Config {
public:
    using fs_path = std::filesystem::path;

    fs_path asset_root;
    fs_path src_list_file;
    fs_path out_dir;
private:
    static Config& CurrentMutable() {
        static Config inst {};
        return inst;
    }
public:
    static const Config& Current() {
        return CurrentMutable();
    }

    /// @return == 0 成功(或提前退出) / != 0 错误
    static int ParseToInstance(int argc, char* argv[]) {
        namespace fs = std::filesystem;

        auto print_version = [] {
            std::cout << "easy resource compiler @ "
                << ercc::VERSION.to_string() << std::endl;
        };
        auto print_usage = [] {
            std::cerr << "usage: erc-compiler --asset-root <dir> "
                "--src-list <file> --out-dir <dir>" << std::endl;
        };
        auto print_help = [&] {
            print_version();
            std::cout << "arguments:"
                "\n\t--asset-root <dir>   Root path of the resource files"
                "\n\t--src-list   <file>  ${target}.list file generated by cmake erc_resource"
                "\n\t--out-dir    <dir>   Output directory for generated ERC-CPP sources"
                "\n\t-h, --help           Print this help"
                "\n\t-v, --version        Print version"
                << std::endl;
        };

        
        std::vector<std::string_view> args;
        if (argc > 1 && argv != nullptr) {
            args.assign(argv + 1, argv + argc);
        }

        std::cout << "[debug] arguments: " << std::endl;
        for (int i = 0; i < args.size(); ++i) {
            std::cout << "[debug] [" << i << "] " << args[i] << std::endl;
        }


        struct ConfigBuffer {
            struct Item {
                std::string value  {};
                bool        exists {false};

                void set(std::string_view v) {
                    value.assign(v); exists = true;
                }
            };
            Item asset_root;
            Item src_list;
            Item out_dir;
        } buf;

        auto set_once = [](ConfigBuffer::Item& item, std::string_view name, std::string_view value) {
            if (item.exists) {
                throw std::invalid_argument("Option set repeatedly: " + std::string(name));
            }
            if (value.empty()) {
                throw std::invalid_argument("Option missing value: " + std::string(name));
            }
            item.set(value);
        };

        /// @brief 匹配 `--opt value` 或 `--opt=value`
        /// @param fn: void(std::string_view name, std::string_view value)
        auto match_then = [&args](std::size_t& i, std::string_view opt, auto&& fn) {
            const std::string_view arg = args[i];
            if (arg == opt) {
                if (i + 1 >= args.size()) {
                    throw std::invalid_argument("Option missing value: " + std::string(opt));
                }
                fn(opt, args[++i]);
                return true;
            }
            if (arg.size() > opt.size() && arg.starts_with(opt) && arg[opt.size()] == '=') {
                fn(opt, arg.substr(opt.size() + 1));
                return true;
            }
            return false;
        };

    
        auto require_dir = [](const fs::path& p) {
            const auto st = fs::status(p);
            if (!fs::exists(st)) {
                throw std::invalid_argument("Path does not exist: " + p.string());
            }
            if (!fs::is_directory(st)) {
                throw std::invalid_argument("Path is not a directory: " + p.string());
            }
        };
        auto require_file = [](const fs::path& p) {
            const auto st = fs::status(p);
            if (!fs::exists(st)) {
                throw std::invalid_argument("Path does not exist: " + p.string());
            }
            if (!fs::is_regular_file(st)) {
                throw std::invalid_argument("Path is not a regular file: " + p.string());
            }
        };

    
        try {
            for (std::size_t i = 0; i < args.size(); ++i) {
                const std::string_view arg = args[i];

                if (arg == "-h" || arg == "--help") {
                    print_help();
                    return 0;
                }
                if (arg == "-v" || arg == "--version") {
                    print_version();
                    return 0;
                }

                if (match_then(i, "--asset-root", std::bind_front(set_once, std::ref(buf.asset_root)))
                 || match_then(i, "--src-list"  , std::bind_front(set_once, std::ref(buf.src_list)))
                 || match_then(i, "--out-dir"   , std::bind_front(set_once, std::ref(buf.out_dir)))
                ) continue;

                throw std::invalid_argument("Unknown argument: " + std::string(arg));
            }


            if (!buf.asset_root.exists) {
                std::cerr << "Missing required option: --asset-root\n";
                print_usage();
                return -3;
            }
            if (!buf.src_list.exists) {
                std::cerr << "Missing required option: --src-list\n";
                print_usage();
                return -4;
            }
            if (!buf.out_dir.exists) {
                std::cerr << "Missing required option: --out-dir\n";
                print_usage();
                return -5;
            }


            require_dir(buf.asset_root.value);
            require_file(buf.src_list.value);
            // @IDEA: 不强制要求 out-dir 必须存在
            // require_dir(buf.out_dir.value);


            Config& inst = Config::CurrentMutable();
            inst.asset_root    = buf.asset_root.value;
            inst.src_list_file = buf.src_list.value;
            inst.out_dir       = buf.out_dir.value;

            return 0;
        }
        catch (const std::invalid_argument& e) {
            std::cerr << e.what() << std::endl;
            print_usage();
            return -1;
        }
        catch (const fs::filesystem_error& e) {
            std::cerr << "filesystem error: " << e.path1();
            if (!e.path2().empty()) std::cerr << " -> " << e.path2();
            std::cerr << ": " << e.what() << std::endl;
            return -e.code().value();
        }
        catch (const std::runtime_error& e) {
            std::cerr << e.what() << std::endl;
            return -2;
        }
    }
};
